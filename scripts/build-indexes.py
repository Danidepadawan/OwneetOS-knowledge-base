STEP = re.compile(r"step-\d+\.\d+[a-z]?-")


def is_step(p):
    return bool(STEP.match(p.stem))


LINK = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]")


def notes_in(folder):
    return sorted(p for p in folder.glob("*.md") if p.name not in ("INDEX.md", "CLAUDE.md"))


def subfolders(folder):
    return sorted(d for d in folder.iterdir()
                  if d.is_dir() and d.name not in SKIP and not d.name.startswith(".") and any(d.rglob("*.md")))


def front(p):
    text = p.read_text()
    if not text.startswith("---\n"):
        return {}
    block = text[4:].split("\n---\n", 1)[0]
    out = {}
    for line in block.splitlines():
        k, _, v = line.partition(":")
        out[k.strip()] = v.strip().strip('"')
    return out


def rel(folder):
    return folder.relative_to(VAULT).as_posix() if folder != VAULT else ""


def index_link(folder, text):
    r = rel(folder)
    return f"[[{r + '/' if r else ''}INDEX|{text}]]"


def step_key(p):
    phase, step, suffix = re.match(r"step-(\d+)\.(\d+)([a-z]?)-", p.stem).groups()
    return int(phase), int(step), suffix   # 4.2, 4.2a, 4.2b, 4.3


def step_title(p):
    m = re.search(r"^# (.*)$", p.read_text(), re.M)
    t = m.group(1) if m else p.stem
    t = re.sub(r"\s*\*\(.*?\)\*", "", t)
    t = re.sub(r"\s*— \*\*Owner input\*\*", "", t)
    t = re.sub(r"\s*\([^()]*;[^()]*\)$", "", t)
    return t.replace("`", "").replace("|", "/")


def phase_progress(folder):
    steps = [p for p in notes_in(folder) if is_step(p)]
    done = sum(1 for p in steps if front(p).get("status") == "done")
    return done, len(steps)


def build(folder):
    key = rel(folder)
    title, desc, intro = FOLDERS.get(key, (folder.name, f"Notes in {key}.", ""))
    if folder.name.startswith("phase-"):
        title = re.search(r"^# (.*)$", (folder / f"{folder.name}.md").read_text(), re.M).group(1)
        desc = f"Steps of {title.split(' — ')[0]} with their status."
    lines = ["---", "type: index", f'description: "{desc}"', "tags: [index]", "---", f"# {title}", ""]
    if intro:
        lines += [intro, ""]
    lines += [GENERATED, ""]
    subs = subfolders(folder)
    if subs:
        lines += ["## Folders", ""]
        for d in subs:
            dtitle, ddesc, _ = FOLDERS.get(rel(d), (d.name, "", ""))
            if d.name.startswith("phase-"):
                done, total = phase_progress(d)
                ddesc = f"{done} of {total} steps done."
                dtitle = re.search(r"^# (.*)$", (d / f"{d.name}.md").read_text(), re.M).group(1)
            lines.append(f"- {index_link(d, dtitle)} — {ddesc}".rstrip(" —"))
        lines.append("")
    notes = notes_in(folder)
    steps = sorted((p for p in notes if is_step(p)), key=step_key)
    others = [p for p in notes if not is_step(p)]
    if others:
        lines += ["## Notes", ""]
        for p in others:
            lines.append(f"- [[{p.stem}]] — {front(p).get('description', '')}")
        lines.append("")
    if steps:
        lines += ["## Steps", "", "Status comes from each step note (`status:`).", ""]
        for p in steps:
            lines.append(f"- `{front(p).get('status', '?')}` [[{p.stem}|{step_title(p)}]] — "
                         f"{front(p).get('description', '')}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def folders():
    out = [VAULT]
    for d in sorted(VAULT.rglob("*")):
        if d.is_dir() and not (SKIP & set(d.relative_to(VAULT).parts)) and not any(
                part.startswith(".") for part in d.relative_to(VAULT).parts) and any(d.rglob("*.md")):
            out.append(d)
    return out


def problems():
    found = []
    all_notes = [p for p in VAULT.rglob("*.md")
                 if not (SKIP & set(p.relative_to(VAULT).parts)) and p.name != "CLAUDE.md"]
    names = {p.stem for p in all_notes} | {"README"}
    paths = {p.relative_to(VAULT).with_suffix("").as_posix() for p in all_notes}
    for p in all_notes:
        if p.name != "INDEX.md" and not front(p).get("description"):
            found.append(f"{p.relative_to(VAULT)}: no description in its front matter")
        body = re.sub(r"`[^`\n]*`", "", p.read_text())
        for target in LINK.findall(body):
            t = target.strip().replace("\\", "")
            if t not in names and t not in paths:
                found.append(f"{p.relative_to(VAULT)}: broken link [[{t}]]")
    return found


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    event = None
    if mode == "--hook":
        try:
            data = json.load(sys.stdin)
        except ValueError:
            data = {}
        event = data.get("hook_event_name")
        target = (data.get("tool_input") or {}).get("file_path")
        if target and VAULT not in Path(target).resolve().parents:
            return 0
    stale = []
    for folder in folders():
        path = folder / "INDEX.md"
        new = build(folder)
        if not path.exists() or path.read_text() != new:
            stale.append(path.relative_to(VAULT).as_posix())
            if mode != "--check":
                path.write_text(new)
    issues = problems()
    if mode == "--check":
        issues += [f"{s}: out of date (run scripts/build-indexes.py)" for s in stale]
    if issues:
        print("\n".join(issues), file=sys.stderr)
        if mode == "--hook":
            return 2 if event == "PostToolUse" else 0
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
