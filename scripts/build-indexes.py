# Builds the INDEX.md of every folder of the vault from the `description:` of each note, and checks
# the vault: every note has a description, every [[link]] resolves. Step lists show the `status:`
# of each step note, which is the only place a step's status is written.
#
#   scripts/build-indexes.py            rebuild every INDEX.md
#   scripts/build-indexes.py --check    exit 1 if an INDEX.md is stale, a description is missing or
#                                       a link is broken (nothing is written)
#   scripts/build-indexes.py --hook     for Claude Code hooks: reads the hook's JSON on stdin; after
#                                       a Write/Edit outside the vault it does nothing; otherwise it
#                                       rebuilds, and reports problems on stderr with exit code 2
#                                       (PostToolUse) so they are fixed at once

